const test = require('node:test');
const assert = require('node:assert/strict');
const Core = require('../src/subtitles.js');

test('parses SRT and sorts cues chronologically', () => {
  const text = '\uFEFF1\r\n00:00:03,000 --> 00:00:04,250\r\nLater\r\n\r\n2\r\n00:00:00,120 --> 00:00:02,000\r\nFirst';
  const cues = Core.parseSubtitleText(text);
  assert.equal(cues.length, 2);
  assert.equal(cues[0].original, 'First');
  assert.equal(cues[0].start, 120);
  assert.equal(cues[1].start, 3000);
});

test('parses WebVTT cue settings and ignores NOTE blocks', () => {
  const text = 'WEBVTT\n\nNOTE generated by test\nignore this\n\n00:00.000 --> 00:02.300 align:start\nHello\nworld';
  const cues = Core.parseSubtitleText(text);
  assert.equal(cues.length, 1);
  assert.equal(cues[0].original, 'Hello\nworld');
  assert.equal(cues[0].end, 2300);
});

test('parses supported timestamps and rejects invalid values', () => {
  const cases = [
    ['00:00:01,250', 1250], ['00:01:02.500', 62500],
    ['01:02:03,004', 3723004], ['02:03,4', 123400]
  ];
  for (const [input, expected] of cases) assert.equal(Core.parseTimestamp(input), expected, input);
  assert.ok(Number.isNaN(Core.parseTimestamp('00:71:00,000')));
  assert.ok(Number.isNaN(Core.parseTimestamp('not-a-time')));
});

test('formats timestamps consistently', () => {
  assert.equal(Core.formatTimestamp(3723004), '01:02:03,004');
  assert.equal(Core.formatTimestamp(-5), '00:00:00,000');
  assert.equal(Core.formatTimestamp(1500, '.'), '00:00:01.500');
});

test('imports original/source aliases and validates project payload', () => {
  const cues = Core.normalizeCues([{ start: 0, end: 1500, source: 'Hello', translation: 'Xin chào' }]);
  assert.equal(cues[0].original, 'Hello');
  assert.equal(cues[0].vi, 'Xin chào');
  assert.throws(() => Core.normalizeCues([{ start: -1, end: 0 }]), /không hợp lệ/);
  assert.throws(() => Core.normalizeCues({ cues: [] }), /mảng cues/);
});

test('exports SRT and VTT in translated, source, and bilingual modes', () => {
  const cues = [Core.createCue(0, 1000, 'Hello', 'Xin chào')];
  assert.match(Core.buildSrt(cues), /Xin chào/);
  assert.match(Core.buildSrt(cues, 'original'), /Hello/);
  assert.match(Core.buildSrt(cues, 'bi'), /Xin chào\nHello/);
  assert.match(Core.buildVtt(cues), /^WEBVTT\n\n/);
  assert.match(Core.buildVtt(cues, 'original'), /Hello/);
});

test('shifts timeline without negative starts and preserves cue durations', () => {
  const cues = [Core.createCue(250, 2250, 'A', ''), Core.createCue(4000, 5500, 'B', '')];
  const shifted = Core.shiftTimeline(cues, -1000);
  assert.equal(shifted[0].start, 0);
  assert.equal(shifted[0].end, 2000);
  assert.equal(shifted[1].start, 3000);
  assert.equal(shifted[1].end, 4500);
  assert.equal(cues[0].start, 250, 'shift must be immutable');
});

test('find and replace operates only on selected fields', () => {
  const cues = [Core.createCue(0, 1000, 'hello hello', 'xin chào')];
  const result = Core.replaceText(cues, 'hello', 'hi', { original: true, vi: false });
  assert.equal(result.cues[0].original, 'hi hi');
  assert.equal(result.cues[0].vi, 'xin chào');
  assert.equal(result.replacements, 1);
  assert.throws(() => Core.replaceText(cues, '', 'x'), /nội dung tìm kiếm/);
});

test('cleans whitespace while preserving line breaks', () => {
  const cue = Core.createCue(0, 1000, '  Hello   there \n   new\t line ', ' Xin   chào ');
  const cleaned = Core.cleanText([cue])[0];
  assert.equal(cleaned.original, 'Hello there\nnew line');
  assert.equal(cleaned.vi, 'Xin chào');
});

test('timeline validator detects missing translations and overlapping cues', () => {
  const a = Core.createCue(0, 2500, 'a', 'A');
  const b = Core.createCue(1000, 1500, 'b', '');
  const issues = Core.validateTimeline([a, b]);
  assert.ok(issues.some((issue) => issue.message.includes('chồng thời gian')));
  assert.ok(issues.some((issue) => issue.message.includes('chưa có bản dịch')));
});
